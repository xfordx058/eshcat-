def _daily_report_pdf(report_date, totals, rows):
    lines = [
        "MUNICIPALITY OF CATARMAN",
        "eSHCAT DAILY COMMUNITY REPORT",
        f"Report date: {report_date}",
        "",
        f"Total reports: {totals['total']}",
        f"Open: {totals['Open']}",
        f"In Progress: {totals['In Progress']}",
        f"Resolved: {totals['Resolved']}",
        "",
        "Reports received today",
    ]
    for row in rows:
        lines.append(f"{row['reference_number']} | {row['category']} | {row['status']}")
        lines.append(f"Location: {row['location'] or '—'}")
        lines.append(f"Description: {row['description'] or '—'}")
        lines.append("")
    if not rows:
        lines.append("No community reports were submitted today.")
    lines.extend(["", "Generated by eSHCAT · Electronic Services Hub of Catarman"])
    pages = [lines[i:i + 42] for i in range(0, len(lines), 42)] or [[]]
    objects = [None, None, b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"]
    page_ids = []
    for page_lines in pages:
        commands = ["BT", "/F1 9 Tf", "50 750 Td", "13 TL"]
        for index, line in enumerate(page_lines):
            safe = line.encode("latin-1", "replace").decode("latin-1")
            escaped = safe.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
            commands.append(f"({escaped}) Tj")
            if index < len(page_lines) - 1:
                commands.append("T*")
        commands.append("ET")
        content = "\n".join(commands).encode("latin-1")
        content_id = len(objects) + 1
        objects.append(f"<< /Length {len(content)} >>\nstream\n".encode("latin-1") + content + b"\nendstream")
        page_id = len(objects) + 1
        objects.append(None)
        page_ids.append((page_id, content_id))
    objects[0] = b"<< /Type /Catalog /Pages 2 0 R >>"
    objects[1] = f"<< /Type /Pages /Kids [{' '.join(f'{page_id} 0 R' for page_id, _ in page_ids)}] /Count {len(page_ids)} >>".encode("latin-1")
    for page_id, content_id in page_ids:
        objects[page_id - 1] = f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R >> >> /Contents {content_id} 0 R >>".encode("latin-1")
    pdf = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = [0]
    for object_id, obj in enumerate(objects, 1):
        offsets.append(len(pdf))
        pdf.extend(f"{object_id} 0 obj\n".encode("latin-1")); pdf.extend(obj); pdf.extend(b"\nendobj\n")
    xref = len(pdf)
    pdf.extend(f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode("latin-1"))
    for offset in offsets[1:]: pdf.extend(f"{offset:010d} 00000 n \n".encode("latin-1"))
    pdf.extend(f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode("latin-1"))
    return bytes(pdf)


def login_required(view):
    @functools.wraps(view)
    def wrapped(*args, **kwargs):
        if session.get("staff_id") is None:
            return jsonify({"error": "Authentication required."}), 401
        return view(*args, **kwargs)

    return wrapped


def admin_required(view):
    @functools.wraps(view)
    @login_required
    def wrapped(*args, **kwargs):
        if session.get("staff_role") != "Administrator":
            return jsonify({"error": "Administrator access required."}), 403
        return view(*args, **kwargs)

    return wrapped


def _department_filter():
    """Return the requested department for administrators, or force staff scope."""
    if session.get("staff_role") == "Administrator":
        return request.args.get("department_id", type=int)
    return session.get("department_id") or -1


def _department_allowed(department_id):
    return session.get("staff_role") == "Administrator" or department_id == session.get("department_id")


@staff_bp.post("/api/staff/login")
def login():
    payload = request.get_json(silent=True) or {}
    email = (payload.get("email") or "").strip().lower()
    password = payload.get("password") or ""

    conn = get_connection()
    try:
        user = conn.execute(
            "SELECT * FROM staff_users WHERE email = ? AND is_active = 1", (email,)
        ).fetchone()
        if user is None or not check_password_hash(user["password_hash"], password):
            return jsonify({"error": "Invalid email or password."}), 401

        session.clear()
        session["staff_id"] = user["id"]
        session["staff_name"] = user["name"]
        session["staff_role"] = user["role"]
        session["department_id"] = user["department_id"]
        session.permanent = True

        log_audit(conn, user["id"], "LOGIN", "staff", user["id"])
        conn.commit()
        return jsonify(
            {
                "id": user["id"],
                "name": user["name"],
                "email": user["email"],
                "role": user["role"],
                "department_id": user["department_id"],
            }
        )
    finally:
        conn.close()


