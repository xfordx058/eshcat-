@staff_bp.get("/api/staff/applications/<int:app_id>")
@login_required
def get_application(app_id):
    conn = get_connection()
    try:
        row = conn.execute(
            """
            SELECT a.*, s.name AS service_name, s.estimated_processing, d.name AS department_name
            FROM applications a
            JOIN services s ON s.id = a.service_id
            JOIN departments d ON d.id = a.department_id
            WHERE a.id = ?
            """,
            (app_id,),
        ).fetchone()
        if row is None:
            return jsonify({"error": "Application not found."}), 404
        if not _department_allowed(row["department_id"]):
            return jsonify({"error": "This application belongs to another department."}), 403
        history = conn.execute(
            """
            SELECT h.*, su.name AS staff_name
            FROM application_history h
            LEFT JOIN staff_users su ON su.id = h.staff_id
            WHERE h.application_id = ?
            ORDER BY h.created_at DESC
            """,
            (app_id,),
        ).fetchall()
        result = dict(row)
        result["form_data"] = json.loads(row["form_data"] or "{}")
        result["history"] = [dict(h) for h in history]
        log_audit(conn, session["staff_id"], "VIEW_APPLICATION", "application", app_id)
        conn.commit()
        return jsonify(result)
    finally:
        conn.close()


@staff_bp.patch("/api/staff/applications/<int:app_id>/status")
@login_required
def patch_status(app_id):
    payload = request.get_json(silent=True) or {}
    new_status = payload.get("status")
    remarks = payload.get("remarks") or ""
    conn = get_connection()
    try:
        row = conn.execute("SELECT department_id FROM applications WHERE id = ?", (app_id,)).fetchone()
    finally:
        conn.close()
    if row is None:
        return jsonify({"error": "Application not found."}), 404
    if not _department_allowed(row["department_id"]):
        return jsonify({"error": "This application belongs to another department."}), 403
    try:
        result = update_status(app_id, session["staff_id"], new_status, remarks)
    except ValueError as exc:
        return jsonify({"error": str(exc)}), 400
    if result is False:
        return jsonify({"error": "Application not found."}), 404
    if not result["changed"]:
        return jsonify({"error": f"Application is already {result['status']}. No status change was made."}), 409
    conn = get_connection()
    try:
        log_audit(conn, session["staff_id"], "UPDATE_STATUS", "application", app_id, new_status)
        conn.commit()
    finally:
        conn.close()
    return jsonify({"message": "Status updated.", "status": new_status, "changed": True})


